    private function insertBatch(string $category, string $difficulty, string $questionType, array $items): void
    {
        foreach ($items as $item) {
            $qid = DB::table('questions')->insertGetId([
                'passage_id'    => null,
                'text'          => $item['text'],
                'difficulty'    => $difficulty,
                'category'      => $category,
                'question_type' => $questionType,
                'explanation'   => $item['explanation'],
                'created_at'    => now(),
                'updated_at'    => now(),
            ]);
            foreach ($item['choices'] as $order => $text) {
                DB::table('choices')->insert([
                    'question_id' => $qid,
                    'text'        => $text,
                    'is_correct'  => ($order === $item['answer']),
                    'order'       => $order,
                ]);
            }
        }
    }

    private function insertBatchWithPassage(string $category, string $difficulty, string $questionType, int $passageId, array $items): void
    {
        foreach ($items as $item) {
            $qid = DB::table('questions')->insertGetId([
                'passage_id'    => $passageId,
                'text'          => $item['text'],
                'difficulty'    => $difficulty,
                'category'      => $category,
                'question_type' => $questionType,
                'explanation'   => $item['explanation'],
                'created_at'    => now(),
                'updated_at'    => now(),
            ]);
            foreach ($item['choices'] as $order => $text) {
                DB::table('choices')->insert([
                    'question_id' => $qid,
                    'text'        => $text,
                    'is_correct'  => ($order === $item['answer']),
                    'order'       => $order,
                ]);
            }
        }
    }
