            foreach (['Kanji','Vocab','Grammar','Reading','文字語彙','文法読解'] as $type) {
                $oldCategories[] = "JLPT-{$level}-{$type}";
            }
        }
        $oldIds = DB::table('questions')->whereIn('category', $oldCategories)->pluck('id');
        if ($oldIds->isNotEmpty()) {
            DB::table('answer_records')->whereIn('question_id', $oldIds)->delete();
            DB::table('choices')->whereIn('question_id', $oldIds)->delete();
            DB::table('questions')->whereIn('id', $oldIds)->update(['deleted_at' => null]);
            DB::table('questions')->whereIn('id', $oldIds)->delete();
        }

        $this->seedN5();
